/** Six rows of block letters. Unknown characters are skipped. */
export function wordmarkRows(text: string): string[] {
  const pieces = [...text.toUpperCase()].flatMap(ch => {
    const glyph = GLYPHS[ch]

    return glyph ? [glyph] : []
  })

  if (!pieces.length) {
    return []
  }

  return Array.from({ length: HEIGHT }, (_, row) => pieces.map(piece => piece[row] ?? '').join('').trimEnd())
}
