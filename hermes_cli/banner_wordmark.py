def wordmark_rows(text: str) -> list[str]:
    """Six rows of block letters. Unknown characters are skipped."""
    pieces = [_GLYPHS[ch] for ch in text.upper() if ch in _GLYPHS]
    if not pieces:
        return []
    return ["".join(piece[row] for piece in pieces).rstrip()
            for row in range(_HEIGHT)]

